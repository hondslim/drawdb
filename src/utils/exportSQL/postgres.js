import { appendViews } from "../views";
import {
  escapeQuotes,
  exportFieldComment,
  parseDefault,
  tableConstraintClause,
  getFkColumnNames,
} from "./shared";
import { dbToTypes } from "../../data/datatypes";
import { diagramSchemas } from "../schema";

function tableRef(table) {
  return table.schema ? `"${table.schema}"."${table.name}"` : `"${table.name}"`;
}

function tablesToPostgres(diagram) {
  const schemaStatements = diagramSchemas(diagram.tables)
    .filter(Boolean)
    .map((schema) => `CREATE SCHEMA IF NOT EXISTS "${schema}";`)
    .join("\n");

  const enumStatements = diagram.enums
    .map(
      (e) =>
        `CREATE TYPE "${e.name}" AS ENUM (\n${e.values
          .map((v) => `\t'${escapeQuotes(String(v))}'`)
          .join(",\n")}\n);\n`,
    )
    .join("\n");

  const typeStatements = diagram.types
    .map(
      (type) =>
        `CREATE TYPE ${type.name} AS (\n${type.fields
          .map((f) => `\t${f.name} ${f.type}`)
          .join(",\n")}\n);${
          type.comment?.trim()
            ? `\n\nCOMMENT ON TYPE "${type.name}" IS '${escapeQuotes(type.comment)}';`
            : ""
        }`,
    )
    .join("\n\n");

  const tableStatements = diagram.tables
    .map((table) => {
      const inheritsClause =
        Array.isArray(table.inherits) && table.inherits.length > 0
          ? `\n) INHERITS (${table.inherits.map((parent) => `"${parent}"`).join(", ")})`
          : "\n)";

      const fieldDefinitions = table.fields
        .map(
          (field) =>
            `${exportFieldComment(field.comment)}\t"${
              field.name
            }" ${field.type}${
              field.size ? `(${field.size})` : ""
            }${field.isArray ? " ARRAY" : ""}${field.notNull ? " NOT NULL" : ""}${
              field.unique ? " UNIQUE" : ""
            }${field.increment ? " GENERATED BY DEFAULT AS IDENTITY" : ""}${
              String(field.default ?? "").trim()
                ? ` DEFAULT ${parseDefault(field, diagram.database)}`
                : ""
            }${
              field.check && dbToTypes[diagram.database][field.type]?.hasCheck
                ? ` CHECK(${field.check})`
                : ""
            }`,
        )
        .join(",\n");

      const primaryKeyClause = table.fields.some((f) => f.primary)
        ? `,\n\tPRIMARY KEY(${table.fields
            .filter((f) => f.primary)
            .map((f) => `"${f.name}"`)
            .join(", ")})`
        : "";

      const uniqueClause = tableConstraintClause(table, (s) => `"${s}"`);

      const commentStatements = [
        table.comment?.trim()
          ? `COMMENT ON TABLE ${tableRef(table)} IS '${escapeQuotes(table.comment)}';`
          : "",
        ...table.fields.map((field) =>
          field.comment?.trim()
            ? `COMMENT ON COLUMN ${tableRef(table)}."${field.name}" IS '${escapeQuotes(field.comment)}';`
            : "",
        ),
      ]
        .filter(Boolean)
        .join("\n");

      const indexStatements = table.indices
        .map(
          (i) =>
            `CREATE ${i.unique ? "UNIQUE " : ""}INDEX "${i.name}"\nON ${tableRef(table)} (${i.fields
              .map((f) => `"${f}"`)
              .join(", ")});`,
        )
        .join("\n");

      return [
        `CREATE TABLE IF NOT EXISTS ${tableRef(table)} (\n${fieldDefinitions}${primaryKeyClause}${uniqueClause}${inheritsClause};`,
        commentStatements,
        indexStatements,
      ]
        .filter(Boolean)
        .join("\n\n");
    })
    .join("\n\n");

  const foreignKeyStatements = diagram.references
    .map((r) => {
      const startTable = diagram.tables.find((t) => t.id === r.startTableId);
      const endTable = diagram.tables.find((t) => t.id === r.endTableId);

      if (!startTable || !endTable) return "";

      const { startColumns, endColumns } = getFkColumnNames(
        r,
        startTable,
        endTable,
      );
      if (startColumns.some((c) => !c) || endColumns.some((c) => !c)) return "";

      return `ALTER TABLE ${tableRef(startTable)}\nADD FOREIGN KEY(${startColumns
        .map((c) => `"${c}"`)
        .join(", ")}) REFERENCES ${tableRef(endTable)}(${endColumns
        .map((c) => `"${c}"`)
        .join(
          ", ",
        )})\nON UPDATE ${r.updateConstraint.toUpperCase()} ON DELETE ${r.deleteConstraint.toUpperCase()};`;
    })
    .filter(Boolean)
    .join("\n");

  return [
    schemaStatements,
    enumStatements,
    typeStatements,
    tableStatements,
    foreignKeyStatements,
  ]
    .map((s) => s.trim())
    .filter(Boolean)
    .join("\n\n");
}

export function toPostgres(diagram) {
  return appendViews(tablesToPostgres(diagram), diagram);
}
