import { describe, expect, it } from "vitest";
import pkg from "node-sql-parser";
import { fromDBML } from "../importFrom/dbml";
import { toDBML } from "../exportAs/dbml";
import { toPostgres } from "../exportSQL/postgres";
import { fromPostgres } from "../importSQL/postgres";
import { mergeShare } from "../share";
import { relationshipFlags } from "../columnDetails";
import { Constraint, DB } from "../../data/constants";

const dbml = `
Table certificates {
  id bigint [pk]
}
Table records {
  id bigint [pk]
  tags text[]
  weight_kg numeric
  weight_g numeric
  email text
  certificate_id bigint
}
Ref: records.certificate_id > certificates.id [delete: cascade]
`;

function diagramFrom(record) {
  return {
    database: DB.POSTGRES,
    types: [],
    enums: [],
    views: [],
    ...record,
    references: record.references ?? record.relationships,
    relationships: record.references ?? record.relationships,
  };
}

describe("arrays in DBML", () => {
  const imported = fromDBML(dbml, DB.POSTGRES);
  const tags = imported.tables[1].fields.find((f) => f.name === "tags");

  it("imports text[] as an array of TEXT and exports it back", () => {
    expect(tags).toMatchObject({ type: "TEXT", isArray: true });
    const out = toDBML(diagramFrom(imported));
    expect(out).toContain("tags text[]");
    expect(toDBML(diagramFrom(fromDBML(out, DB.POSTGRES)))).toEqual(out);
  });
});

describe("column details from share metadata", () => {
  const imported = fromDBML(dbml, DB.POSTGRES);
  const record = mergeShare(
    {
      title: "t",
      database: DB.POSTGRES,
      tables: imported.tables,
      relationships: imported.relationships,
      postgres: {
        columns: [
          { table: "records", column: "id", identity: "ALWAYS" },
          {
            table: "records",
            column: "weight_g",
            generated: "weight_kg * 1000",
          },
          {
            table: "public.records",
            column: "email",
            domain: "digivacc.email",
          },
        ],
        foreignKeys: [
          {
            table: "records",
            columns: ["certificate_id"],
            deferrable: true,
            initiallyDeferred: true,
          },
        ],
      },
    },
    null,
    "X",
  );
  const records = record.tables.find((t) => t.name === "records");
  const field = (name) => records.fields.find((f) => f.name === name);

  it("sets identity, generated and domain on fields", () => {
    expect(field("id").identity).toBe("ALWAYS");
    expect(field("weight_g").generated).toBe("weight_kg * 1000");
    expect(field("email").domain).toBe("digivacc.email");
    expect(field("tags").identity).toBeUndefined();
  });

  it("marks the FK deferrable", () => {
    expect(record.references[0].deferrable).toBe("DEFERRED");
  });

  it("labels cascading and deferrable relationships", () => {
    expect(relationshipFlags(record.references[0])).toEqual([
      "CASCADE",
      "DEFERRED",
    ]);
    expect(
      relationshipFlags({ deleteConstraint: Constraint.SET_NULL }),
    ).toEqual(["SET NULL"]);
    expect(relationshipFlags({ deleteConstraint: Constraint.NONE })).toEqual(
      [],
    );
  });

  it("exports identity, generated columns and deferrable FKs", () => {
    const sql = toPostgres(diagramFrom(record));
    expect(sql).toContain('"id" BIGINT GENERATED ALWAYS AS IDENTITY');
    expect(sql).toContain(
      '"weight_g" NUMERIC GENERATED ALWAYS AS (weight_kg * 1000) STORED',
    );
    expect(sql).toContain('"tags" TEXT ARRAY');
    expect(sql).toContain("ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED;");
  });
});

describe("column details from Postgres SQL", () => {
  const ast = new pkg.Parser().astify(
    `CREATE TABLE a (id bigint GENERATED BY DEFAULT AS IDENTITY, tags text[], nums int[]);`,
    { database: "postgresql" },
  );
  const [a] = fromPostgres(ast, DB.POSTGRES).tables;

  it("reads BY DEFAULT identity and arrays", () => {
    expect(a.fields[0]).toMatchObject({
      identity: "BY DEFAULT",
      increment: true,
    });
    expect(a.fields[1]).toMatchObject({ type: "TEXT", isArray: true });
    expect(a.fields[2]).toMatchObject({ isArray: true });
  });
});
